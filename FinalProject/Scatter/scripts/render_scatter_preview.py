import os,sys
import hou,numpy as np
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__))).replace('\\','/')
SCENE=sys.argv[1] if len(sys.argv)>1 else ROOT+'/Scatter_Pile.hipnc'
PREVIEW=sys.argv[2] if len(sys.argv)>2 else ROOT+'/render/Scatter_Pile_Preview.png'
hou.hipFile.load(SCENE,suppress_save_prompt=True,ignore_load_warnings=True)
for path in ['/obj/PREVIEW_GROUND','/obj/Pile_Preview_Camera','/obj/Preview_Key','/obj/Preview_Fill','/obj/Preview_Rim',
             '/mat/Scrap_Metal_And_Rubber','/mat/Ground_Matte','/out/RENDER_PILE_PREVIEW']:
    old=hou.node(path)
    if old:old.destroy()
obj=hou.node('/obj/SCATTER_PILE')
normal=obj.node('SOURCE_NORMALS') or obj.createNode('normal','SOURCE_NORMALS')
normal.setInput(0,obj.node('SOURCE_15_LOW_POLY_ASSETS'))
obj.node('PACK_BY_ASSET_NAME').setInput(0,normal)
normal.setPosition(hou.Vector2((-1,4)))
mat=hou.node('/mat').createNode('principledshader::2.0','Scrap_Metal_And_Rubber')
mat.parmTuple('basecolor').set((1,1,1));mat.parm('basecolor_usePointColor').set(1)
mat.parm('rough').set(.72);mat.parm('metallic').set(.28)
obj.parm('shop_materialpath').set(mat.path())
floor=hou.node('/obj').createNode('geo','PREVIEW_GROUND')
for n in floor.children():n.destroy()
grid=floor.createNode('grid','Ground');grid.parmTuple('size').set((200,200));grid.parm('rows').set(2);grid.parm('cols').set(2)
groundmat=hou.node('/mat').createNode('principledshader::2.0','Ground_Matte')
groundmat.parmTuple('basecolor').set((.12,.14,.16));groundmat.parm('rough').set(.95)
floor.parm('shop_materialpath').set(groundmat.path())
def aim(node,eye,target):
    eye=np.array(eye,dtype=float);target=np.array(target,dtype=float)
    backward=eye-target;backward/=np.linalg.norm(backward)
    right=np.cross([0,1,0],backward);right/=np.linalg.norm(right)
    up=np.cross(backward,right)
    R=hou.Matrix3(np.array([right,up,backward]).flatten().tolist())
    node.parmTuple('t').set(eye.tolist());node.parmTuple('r').set(R.extractRotates())
camera=hou.node('/obj').createNode('cam','Pile_Preview_Camera')
aim(camera,(3.4,3.5,4.6),(0,.32,0))
camera.parm('projection').set('ortho')
controls=obj if obj.parm('length_cm') else obj.node('CONTROLS')
camera.parm('orthowidth').setExpression('max(1.3,1.55*max(ch("%s/length_cm"),ch("%s/width_cm"))/100)'%(controls.path(),controls.path()))
camera.parmTuple('res').set((1400,1050));camera.parm('near').set(.01)
for name,pos,power,color in [('Key',(-3,5,4),.95,(1.,.88,.74)),('Fill',(4,3,2),.4,(.72,.84,1.)),('Rim',(1,4,-4),.65,(1.,.93,.82))]:
    light=hou.node('/obj').createNode('hlight','Preview_'+name)
    light.parm('light_type').set('distant');light.parm('light_intensity').set(power)
    light.parmTuple('light_color').set(color);aim(light,pos,(0,.2,0))
    light.parm('shadow_bias').set(.001)
rop=hou.node('/out').createNode('ifd','RENDER_PILE_PREVIEW')
rop.parm('camera').set(camera.path());rop.parm('vm_picture').set(PREVIEW)
rop.parm('vm_renderengine').set('pbrraytrace')
rop.parm('vm_samplesx').set(3);rop.parm('vm_samplesy').set(3);rop.parm('vm_diffuselimit').set(0)
rop.parm('vm_maxraysamples').set(4)
hou.node('/obj').layoutChildren();hou.node('/mat').layoutChildren()
obj.node('OUT_SCATTER').setDisplayFlag(True);obj.node('OUT_SCATTER').setRenderFlag(True)
obj.setSelected(True,clear_all_selected=True)
hou.hipFile.save(SCENE)
print('RENDER_START',flush=True)
rop.render(frame_range=(1,1))
print('RENDER_COMPLETE',PREVIEW,flush=True)
