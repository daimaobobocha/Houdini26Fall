import hou,os,shutil,json
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__))).replace('\\','/')
SOURCE=ROOT+'/backup/ICA10_before_stair_continuation.hipnc'
if not os.path.exists(SOURCE):shutil.copy2(ROOT+'/ICA10.hipnc',SOURCE)
hou.hipFile.load(SOURCE,suppress_save_prompt=True,ignore_load_warnings=True)
hou.hipFile.setName(ROOT+'/ICA10.hipnc')
g=hou.node('/obj/geo1')
g.setName('STAIRCASE',unique_name=True)
def expr(n,p,s):
    parm=n.parm(p);parm.deleteAllKeyframes();parm.setExpression(s,hou.exprLanguage.Hscript)
def comment(n,s):
    n.setComment(s);n.setGenericFlag(hou.nodeFlag.DisplayComment,True)
def new(typ,name,src=None,parms=None):
    n=g.createNode(typ,name)
    if src:n.setInput(0,src)
    if parms:n.setParms(parms)
    return n

# Repair references in the student's existing network before encapsulation.
g.node('object_merge1').parm('objpath1').set('../OUT_Step')
g.node('object_merge2').parm('objpath1').set('../OUT_landing')
wr=g.node('pointwrangle1')
wr.parm('snippet').set(wr.evalParm('snippet').replace('/obj/geo1/pointwrangle1/length','length'))
wr.parm('class').set(3)
comment(wr,'Extend the two handrail ends down by the promoted rail height. Detail mode creates each end exactly once.')
for name in ('sweep2','sweep3'):
    expr(g.node(name),'radius','ch("../grid1/sizey") * 0.5')
    g.node(name).parm('endcaptype').set(1)
    g.node(name).parm('cols').set(16)
g.node('grouprange3').parm('grouptype1').set(0)
g.node('copytopoints3').parm('targetgroup').set('group_pillar')
expr(g.node('copy2'),'tx','ch("../copy1/tx")')
for name in ('clip1','clip2'):
    g.node(name).parm('dofill').set(1)
    comment(g.node(name),'Class continuation: Build Polygon Cappings enabled so stringers remain closed solid geometry in Unreal.')

# Four intermediate guard rails follow the original trimmed staircase curve.
sweep=new('sweep::2.0','sweep4_midrails',g.node('carve2'),{'surfaceshape':1,'cols':16,'endcaptype':1})
expr(sweep,'radius','ch("../grid1/sizey") * 0.5 * 0.85')
uv=new('uvflatten::3.0','uvflatten6_midrails',sweep)
copy=new('copyxform','copy3_midrails',uv,{'ncy':4})
expr(copy,'ty','ch("../pointwrangle1/length") / (ch("ncy") + 1)')
shift=new('xform','transform2_midrails',copy)
expr(shift,'ty','-ch("../pointwrangle1/length") + ch("../copy3_midrails/ty")')
midout=new('null','OUT_Midrail',shift)
comment(copy,'Four midrails. Height / (count + 1) keeps a clear gap above the stringer and below the main handrail, as discussed in class.')
g.node('object_merge3').setParms({'numobj':3,'objpath3':'../OUT_Midrail'})

# Name the four construction branches while retaining the original SOP workflow.
parts=[('TREADS',g.node('OUT_Landing'),'treads'),('LANDINGS',g.node('OUT_Steps'),'landings'),('STRINGERS',g.node('OUT_Stringer'),'stringers'),('RAILS',g.node('transform1'),'rails')]
for i,(name,src,label) in enumerate(parts):
    tag=new('attribwrangle','TAG_'+name,src,{'class':1,'snippet':'s@name = "'+label+'"; setprimgroup(0, "'+label+'", @primnum, 1);'})
    g.node('merge1').setInput(i,tag)
norm=new('normal','normal_final',g.node('merge1'),{'cuspangle':60})
out=new('null','OUT_STAIRCASE',norm)
out.setDisplayFlag(True);out.setRenderFlag(True)
out.setColor(hou.Color((.25,.8,.45)))
comment(out,'Complete classroom staircase: treads, landings, capped stringers, main handrails, posts and four intermediate rails.')

curve=g.node('curve1')
comment(curve,'Editable original guide curve. Begin with an ascending flight toward -Z, then alternate a horizontal landing and another flight. The guide stays outside the HDA.')
sub=g.collapseIntoSubnet(tuple(n for n in g.children() if n!=curve),'ICA10_Stairs')
sub.setDisplayFlag(True);sub.setRenderFlag(True)
ptg=hou.ParmTemplateGroup()
ptg.append(hou.FloatParmTemplate('size','Step Size (Width / Thickness / Depth)',3,default_value=(10,.2,2)))
ptg.append(hou.FloatParmTemplate('length','Step Spacing',1,default_value=(1.5,),min=.05,min_is_strict=True))
ptg.append(hou.IntParmTemplate('offset','Step Count Offset (Start / End)',2,default_value=(1,1),min=0,min_is_strict=True,naming_scheme=hou.parmNamingScheme.Base1))
ptg.append(hou.FloatParmTemplate('railheight','Handrail Height',1,default_value=(4,),min=.1,min_is_strict=True))
ptg.append(hou.IntParmTemplate('midrailcount','Intermediate Rail Count',1,default_value=(4,),min=1,max=10,min_is_strict=True,max_is_strict=True))
ptg.append(hou.FloatParmTemplate('stringersize','Stringer Profile (Depth / Thickness)',2,default_value=(2,.2),min=.01,min_is_strict=True))
ptg.append(hou.LabelParmTemplate('guide_help','Guide: alternate rising flights and level landings, heading toward -Z.'))
sub.setParmTemplateGroup(ptg)
for axis in 'xyz':expr(sub.node('box1'),'size'+axis,'ch("../size'+axis+'")')
expr(sub.node('resample1'),'length','ch("../length")')
expr(sub.node('grouprange2'),'start1','ch("../offset1")')
expr(sub.node('grouprange2'),'end1','ch("../offset2")')
expr(sub.node('pointwrangle1'),'length','ch("../railheight")')
expr(sub.node('copy3_midrails'),'ncy','ch("../midrailcount")')
expr(sub.node('grid1'),'sizex','ch("../stringersizex")')
expr(sub.node('grid1'),'sizey','ch("../stringersizey")')
comment(sub,'ICA10 completed from the original student network. Input 1: editable staircase guide curve. Promoted size, spacing, endpoint trim, handrail height and midrail count.')
sub.layoutChildren()
geo=sub.geometry()
print('PRE_HDA',len(geo.points()),len(geo.prims()),sub.errors(),flush=True)
assert geo.prims() and not sub.errors()
os.makedirs(ROOT+'/hda',exist_ok=True)
asset=sub.createDigitalAsset(name='ica10::procedural_stairs::1.0',hda_file_name=ROOT+'/hda/ICA10_Stairs.hdanc',description='ICA10 Procedural Stairs',min_num_inputs=1,max_num_inputs=1,compress_contents=True)
asset.type().definition().setParmTemplateGroup(ptg)
asset.type().definition().addSection('Help','ICA10 staircase continuation.\nInput 1 is a polygon guide curve. Begin with a rising flight in -Z and alternate with a level landing.\nSize controls width, thickness and tread depth. Spacing controls the resampling interval.\nStart/End Offset removes endpoint treads to avoid overlapping landings.\nIncludes closed stringer caps and four intermediate rails. Original SOP construction is retained.\n')
asset.type().definition().updateFromNode(asset)
asset.matchCurrentDefinition()
asset.setSelected(True,clear_all_selected=True)
g.layoutChildren()
hou.hda.installFile(ROOT+'/hda/ICA10_Stairs.hdanc',change_oplibraries_file=False)
hou.hipFile.save(ROOT+'/ICA10.hipnc')
os.makedirs(ROOT+'/geo',exist_ok=True)
asset.geometry().saveToFile(ROOT+'/geo/ICA10_Stairs.bgeo.sc')
export=g.createNode('rop_fbx','EXPORT_STAIR_FBX')
export.setInput(0,asset)
os.makedirs(ROOT+'/export',exist_ok=True)
export.parm('sopoutput').set('$HIP/export/ICA10_Stairs.fbx')
export.parm('execute').pressButton()
asset.setDisplayFlag(True);asset.setRenderFlag(True)
hou.hipFile.save()
print('FINISHED',hou.hipFile.path(),asset.path(),len(asset.geometry().prims()),flush=True)

